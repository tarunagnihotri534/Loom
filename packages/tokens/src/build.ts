import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { resolveTokens } from "./resolve.js";
import { auditContrast } from "./contrast.js";
import { tokensConfig, contrastAuditPairs } from "./tokens.config.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function build() {
  console.log("🔨 [Loom Tokens] Resolving token configuration...");

  // Step 1: Resolve & validate 3-layer architecture
  const resolved = resolveTokens(tokensConfig);
  console.log("  ✓ Token layering validated: Primitive -> Semantic -> Component.");

  // Step 2: WCAG AA Contrast Audit
  console.log("🔍 [Loom Tokens] Running WCAG AA (4.5:1) contrast audit...");
  const auditResults = auditContrast(resolved, contrastAuditPairs);
  console.log(`  ✓ Audited ${auditResults.length} contrast checks across light & dark modes. All passed!`);

  // Step 3: Prepare output directories
  const tokensDistDir = path.resolve(__dirname, "../dist");
  const cssSrcDir = path.resolve(__dirname, "../../css/src");

  if (!fs.existsSync(tokensDistDir)) {
    fs.mkdirSync(tokensDistDir, { recursive: true });
  }
  if (!fs.existsSync(cssSrcDir)) {
    fs.mkdirSync(cssSrcDir, { recursive: true });
  }

  // Step 4: Generate tokens.css
  const lightVars = Object.entries(resolved.light.cssVariables)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n");

  const darkVars = Object.entries(resolved.dark.cssVariables)
    // Only emit dark variables that differ from light mode
    .filter(([k, v]) => resolved.light.cssVariables[k] !== v)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n");

  const cssContent = `/**
 * DO NOT EDIT DIRECTLY.
 * This file is automatically generated by loom-design-system-tokens build.
 * Edit packages/tokens/src/tokens.config.ts instead.
 */

:root {
${lightVars}
}

.dark {
${darkVars}
}
`;

  const cssPath = path.join(cssSrcDir, "tokens.css");
  fs.writeFileSync(cssPath, cssContent, "utf-8");
  console.log(`  ✓ Generated CSS variables: ${cssPath}`);

  // Step 5: Generate tokens.json
  const tokenData = {
    $schema: "https://loom.design/schema/tokens.json",
    primitive: resolved.primitive,
    light: resolved.light.tokens,
    dark: resolved.dark.tokens,
    cssVariables: {
      light: resolved.light.cssVariables,
      dark: resolved.dark.cssVariables,
    },
  };
  const jsonContent = JSON.stringify(tokenData, null, 2);
  const jsonPath = path.join(tokensDistDir, "tokens.json");
  fs.writeFileSync(jsonPath, jsonContent, "utf-8");
  console.log(`  ✓ Generated JSON tokens: ${jsonPath}`);

  // Step 6: Generate ESM and CJS JavaScript entries
  const esmContent = `/**
 * DO NOT EDIT DIRECTLY.
 * This file is automatically generated by loom-design-system-tokens build.
 */
export const tokens = ${jsonContent};
export default tokens;
`;
  const esmPath = path.join(tokensDistDir, "index.js");
  fs.writeFileSync(esmPath, esmContent, "utf-8");

  const cjsContent = `/**
 * DO NOT EDIT DIRECTLY.
 * This file is automatically generated by loom-design-system-tokens build.
 */
const tokens = ${jsonContent};
module.exports = tokens;
module.exports.tokens = tokens;
module.exports.default = tokens;
`;
  const cjsPath = path.join(tokensDistDir, "index.cjs");
  fs.writeFileSync(cjsPath, cjsContent, "utf-8");
  console.log(`  ✓ Generated ESM & CJS JavaScript modules: ${esmPath}, ${cjsPath}`);

  // Step 7: Generate TypeScript declaration file (tokens.d.ts)
  const tokenKeys = Object.keys(resolved.light.tokens)
    .map((k) => `  | "${k}"`)
    .join("\n");

  const cssVarKeys = Object.keys(resolved.light.cssVariables)
    .map((k) => `  | "${k}"`)
    .join("\n");

  const dtsContent = `/**
 * DO NOT EDIT DIRECTLY.
 * This file is automatically generated by loom-design-system-tokens build.
 */

export type LoomTokenKey =
${tokenKeys};

export type LoomCssVariable =
${cssVarKeys};

export interface ResolvedTokenSystem {
  $schema: string;
  primitive: Record<string, string | number>;
  light: Record<LoomTokenKey, string | number>;
  dark: Record<LoomTokenKey, string | number>;
  cssVariables: {
    light: Record<LoomCssVariable, string | number>;
    dark: Record<LoomCssVariable, string | number>;
  };
}

export declare const tokens: ResolvedTokenSystem;
export default tokens;
`;

  const dtsPath = path.join(tokensDistDir, "tokens.d.ts");
  fs.writeFileSync(dtsPath, dtsContent, "utf-8");
  console.log(`  ✓ Generated TypeScript declarations: ${dtsPath}`);

  console.log("✨ [Loom Tokens] Build completed successfully!\n");
}

build().catch((err) => {
  console.error("❌ [Loom Tokens Build Failed]");
  console.error(err.message || err);
  process.exit(1);
});
